func TestCreateMySQL(t *testing.T) {
	tests := map[string]struct {
		num      int
		title    string
		files    []string
		wantErr  bool
		wantNum  int
		wantUp   string
		wantDown string
	}{
		"initial": {
			num: -1, title: "first_migration",
			files:   []string{"000000_init.all.sql"},
			wantNum: 10, wantUp: "VALUES (10, 'first_migration'", wantDown: "CALL _migration_exists(10)",
		},
		"subsequent": {
			num: -1, title: "second_migration",
			files:   []string{"000000_init.all.sql", "000010_first.up.sql", "000010_first.down.sql"},
			wantNum: 20, wantUp: "VALUES (20, 'second_migration'", wantDown: "CALL _migration_exists(20)",
		},
		"specific number": {
			num: 5, title: "specific_migration",
			files:   []string{"000000_init.all.sql", "000010_first.up.sql", "000010_first.down.sql"},
			wantNum: 5, wantUp: "VALUES (5, 'specific_migration'", wantDown: "CALL _migration_exists(5)",
		},
		"duplicate": {
			num: 10, title: "duplicate_migration",
			files:   []string{"000000_init.all.sql", "000010_first.up.sql", "000010_first.down.sql"},
			wantErr: true,
		},
	}
	for name, test := range tests {
		t.Run(name, func(t *testing.T) {
			dir := t.TempDir()
			for _, f := range test.files {
				if err := os.WriteFile(filepath.Join(dir, f), []byte("-- dummy"), 0666); err != nil {
					t.Fatal(err)
				}
			}
			err := Create(io.Discard, dir, test.title, test.num, "migy", my)
			if (err != nil) != test.wantErr {
				t.Fatalf("error = %v, wantErr %v", err, test.wantErr)
			}
			if test.wantErr {
				return
			}
			mig := migrations.Migration{Number: test.wantNum, Title: test.title}
			up, err := os.ReadFile(filepath.Join(dir, mig.UpName()))
			if err != nil {
				t.Fatal(err)
			}
			if !strings.HasPrefix(string(up), "-- Generated by migy (") || !strings.Contains(string(up), test.wantUp) {
				t.Errorf("up file: %s", up)
			}
			down, err := os.ReadFile(filepath.Join(dir, mig.DownName()))
			if err != nil {
				t.Fatal(err)
			}
			if !strings.Contains(string(down), test.wantDown) {
				t.Errorf("down file: %s", down)
			}
		})
	}
}
