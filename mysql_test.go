func TestFormatStatus(t *testing.T) {
	newMig := func(num int, title string, updown, snapshot bool) *migrations.Migration {
		return &migrations.Migration{Number: num, Title: title, UpDown: updown, Snapshot: snapshot}
	}
	tests := map[string]struct {
		st  migrations.Status
		exp string
	}{
		"init": {
			migrations.Status{Migration: newMig(0, "init", false, true)},
			"000000\t　　⏺\t　0000-00-00 --:--:--\t\"init\"",
		},
		"applied": {
			migrations.Status{
				Migration: newMig(10, "first", true, false),
				Applied:   time.Date(2025, 9, 4, 10, 20, 30, 0, time.UTC),
			},
			"000010\t⏫⏬　\t✅2025-09-04 10:20:30\t\"first\"",
		},
		"with-snapshot": {
			migrations.Status{
				Migration: newMig(20, "second", true, true),
				Applied:   time.Date(2025, 9, 5, 20, 30, 40, 0, time.UTC),
				DBTitle:   "db-second",
			},
			"000020\t⏫⏬⏺\t✅2025-09-05 20:30:40\t⚠\"second\" DB:\"db-second\"",
		},
	}
	for name, test := range tests {
		t.Run(name, func(t *testing.T) {
			if d := cmp.Diff(test.exp, string(formatStatus(nil, test.st))); d != "" {
				t.Error(d)
			}
		})
	}
}

