func TestCheckMySQL(t *testing.T) {
	dir := filepath.Join("testdata", "mysql", "check")
	tests := map[string]struct {
		dir  string
		num  int
		diff string
	}{
		"success-create":     {"success", 10, ""},
		"success-alter-add":  {"success", 20, ""},
		"success-insert":     {"success", 30, ""},
		"success-alter-drop": {"success", 40, ""},
		"success-nothing":    {"success", 50, ""},
		"diff-table": {
			"table", 10,
			`unexpected table "table1" found`,
		},
		"diff-schema": {
			"schema", 20,
			"" +
				"table \"table1\" differs:\n" +
				"...\n" +
				"   `val` text NOT NULL DEFAULT '',\n" +
				"+  `val2` int DEFAULT '0',\n" +
				"   PRIMARY KEY (`id`)\n" +
				"...",
		},
		"diff-record": {
			"record", 30,
			"" +
				"records in \"table1\" differs:\n" +
				"+(2, 'bbb', 20)",
		},
		"diff-snapshot": {
			"snapshot", 30,
			"" +
				"records in \"table1\" differs:\n" +
				" (1, 'aaa', 10)\n" +
				"-(2, 'bbb', 200)\n" +
				"+(2, 'bbb', 20)\n" +
				" (3, 'ccc', 30)",
		},
		"diff-column": {
			"column", 40,
			"" +
				"records in \"table1\" differs:\n" +
				"-(1, 'aaa', 10)\n" +
				"-(2, 'bbb', 20)\n" +
				"-(3, 'ccc', 30)\n" +
				"+(1, '', 10)\n" +
				"+(2, '', 20)\n" +
				"+(3, '', 30)",
		},
		"diff-drop": {
			"drop", 50,
			`missing table "table1"`,
		},
	}
	for name, test := range tests {
		t.Run(name, func(t *testing.T) {
			diff, err := Check(io.Discard, filepath.Join(dir, test.dir), test.num, my)
			if err != nil {
				t.Fatal(err)
			}
			if d := cmp.Diff(test.diff, diff); d != "" {
				t.Error(d)
			}
		})
	}
}

func copyFiles(t *testing.T, src, dst string, files ...string) {
	t.Helper()
	for _, f := range files {
		b, err := os.ReadFile(filepath.Join(src, f))
		if err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(filepath.Join(dst, f), b, 0666); err != nil {
			t.Fatal(err)
		}
	}
}

func TestSnapshotMySQL(t *testing.T) {
	dir := t.TempDir()
	copyFiles(t, filepath.Join("testdata", "mysql", "snapshot"), dir,
		"000000_init.all.sql",
		"000010_create_users.up.sql",
		"000010_create_users.down.sql",
		"000020_alter_users.up.sql",
		"000020_alter_users.down.sql",
	)

	// expected states
	db, err := my.OpenTemp()
	if err != nil {
		t.Fatal(err)
	}
	if err := applyFiles(io.Discard, db, my, dir, "000000_init.all.sql", "000010_create_users.up.sql"); err != nil {
		t.Fatal(err)
	}
	ss10, err := my.TakeSnapshot(db)
	if err != nil {
		t.Fatal(err)
	}
	if err := applyFiles(io.Discard, db, my, dir, "000020_alter_users.up.sql"); err != nil {
		t.Fatal(err)
	}
	ss20, err := my.TakeSnapshot(db)
	if err != nil {
		t.Fatal(err)
	}
	db.Close()

	tests := map[string]struct {
		num  int
		file string
		exp  *dbstate.Snapshot
	}{
		"snapshot10": {10, "000010_create_users.all.sql", ss10},
		"snapshot20": {-1, "000020_alter_users.all.sql", ss20},
	}
	for name, test := range tests {
		t.Run(name, func(t *testing.T) {
			path, err := SnapshotFile(dir, test.num)
			if err != nil {
				t.Fatal(err)
			}
			if exp := filepath.Join(dir, test.file); path != exp {
				t.Fatalf("SnapshotFile: %v wants %v", path, exp)
			}

			var buf bytes.Buffer
			if err := Snapshot(io.Discard, &buf, dir, test.num, "migy", my); err != nil {
				t.Fatal(err)
			}
			if !strings.HasPrefix(buf.String(), "-- Generated by migy (") {
				t.Errorf("no signature: %q", buf.String()[:40])
			}
			if err := os.WriteFile(path, buf.Bytes(), 0666); err != nil {
				t.Fatal(err)
			}

			db, err := OpenDumpFile(my, path)
			if err != nil {
				t.Fatal(err)
			}
			defer db.Close()
			ss, err := my.TakeSnapshot(db)
			if err != nil {
				t.Fatal(err)
			}
			if diff := dbstate.Diff(test.exp, ss, dbstate.DiffOptions{Ignores: snapshotIgnores}); diff != "" {
				t.Fatal("diff snapshot:\n" + diff)
			}

			// the same state always gives the same file
			var buf2 bytes.Buffer
			if err := Snapshot(io.Discard, &buf2, dir, test.num, "migy", my); err != nil {
				t.Fatal(err)
			}
			if !bytes.Equal(withoutApplied(buf.Bytes()), withoutApplied(buf2.Bytes())) {
				t.Errorf("not deterministic:\n%s\n----\n%s", buf.Bytes(), buf2.Bytes())
			}
		})
	}
}

// withoutApplied removes the timestamps of '_migrations.applied'
func withoutApplied(b []byte) []byte {
	var out [][]byte
	for _, l := range bytes.Split(b, []byte("\n")) {
		if i := bytes.Index(l, []byte(", '20")); i >= 0 {
			l = l[:i]
		}
		out = append(out, l)
	}
	return bytes.Join(out, []byte("\n"))
}

